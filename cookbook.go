// parse возвращает номер рецепта, 0 при ошибке ввода.
// Выход из программы обозначается отдельным флагом.
func parse(s string) (int, bool) {
	if len(s) < 1 || len(s) > 3 {
		return 0, false
	}
	n := 0
	for i := 0; i < len(s); i++ {
		if s[i] < '0' || s[i] > '9' {
			return 0, false
		}
		n = n*10 + int(s[i]-'0')
	}
	return n, true
}

