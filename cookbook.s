# ------------------------------------------------------------
#  print_str(rdi = fd, rsi = указатель на строку с \0)
#  портит: rax, rcx, rdi, rsi, rdx, r11
# ------------------------------------------------------------
	.text
	.globl	_start
	.type	_start, @function
_start:
	cld
	xor	%r10, %r10			# счётчик выбора

.Lloop:
	mov	$STDOUT, %edi
	lea	menu(%rip), %rsi
	call	print_str

	# читаем ровно один байт
	xor	%eax, %eax
	mov	$STDIN, %edi
	lea	inbuf(%rip), %rsi
	mov	$1, %edx
	syscall
	cmp	$1, %rax
	jne	.Lquit			# EOF или ошибка -> выход

	movzbl	inbuf(%rip), %ecx	# символ
	sub	$ASCII_0, %ecx		# '0' -> 0 ... '9' -> 9
	cmp	$ASCII_9, %ecx
	ja	.Lbad			# не цифра

	test	%ecx, %ecx
	jnz	.Ldigit
	mov	$9, %ecx			# '0' -> рецепт 10
	jmp	.Lhave
.Ldigit:
	sub	$1, %ecx			# '1' -> 0 ... '9' -> 8

.Lhave:
	lea	recipes(%rip), %rbx
	mov	(%rbx,%rcx,8), %rsi
	mov	$STDOUT, %edi
	call	print_str
	jmp	.Lloop

.Lbad:
	mov	$STDOUT, %edi
	lea	msg_bad(%rip), %rsi
	call	print_str
	jmp	.Lloop

.Lquit:
	xor	%edi, %edi
	mov	$SYS_exit, %eax
	syscall

	.size	_start, . - _start

# ------------------------------------------------------------
#  print_str — вывод NUL-строки через write(2)
#  вход: %edi = fd, %rsi = ptr
# ------------------------------------------------------------
	.type	print_str, @function
print_str:
	push	%rdi			# fd
	push	%rsi
	mov	%rsi, %r8		# начало строки
	mov	%rsi, %rdi		# rdi -> конец строки
	xor	%eax, %eax
	mov	$-1, %ecx			# безграничный поиск \0
	repne	scasb			# rdi уходит ЗА найденный \0
	mov	%rdi, %rdx
	sub	%r8, %rdx
	dec	%rdx			# длина без \0
	pop	%rsi			# ptr для write(2)
	pop	%rdi			# fd  для write(2)
	mov	$SYS_write, %eax
	syscall
	ret
	.size	print_str, . - print_str

